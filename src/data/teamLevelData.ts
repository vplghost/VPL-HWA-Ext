/**
 * Returns the experience delta required for the given level to reach the next level.
 * Returns null if level is invalid (< 1).
 * Returns 0 if level is at max level (120).
 */
export function getTeamLevelExpDelta(level: number | null | undefined): number | null {
  if (level == null || !Number.isFinite(Number(level))) return null;
  const num = Math.floor(Number(level));
  if (num < 1 || num > 120) return null;
  return TEAM_LEVEL_DELTAS[num] ?? null;
}
