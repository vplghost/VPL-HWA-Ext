import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const index = JSON.parse(await readFile('temp/remote-config-captured.json', 'utf8')).index.configs;
const sources = {};
async function config(name) {
  const bytes = await readFile(`temp/smart-gather-${name}.json`);
  const md5 = createHash('md5').update(bytes).digest('hex');
  const url = index[name]?.url;
  if (!url?.endsWith(`/${md5}.json`)) throw Error(`Config hash mismatch: ${name}`);
  sources[name] = { url, md5 };
  return JSON.parse(bytes);
}
const quests = await config('quest'), chains = await config('questChain'), mines = await config('globalMapMine');
const daily = {};
for (const [type, firstId] of Object.entries({ food: 354, iron: 357, stone: 356, wood: 355 })) {
  const first = quests[firstId];
  if (!chains[first.chainId]?.transferProgress) throw Error('Daily progress does not transfer');
  const steps = Object.values(quests).filter(q => q.chainId === first.chainId).sort((a, b) => a.chainOrder - b.chainOrder);
  if (steps.some(q => q.condition?.name !== 'globalMapResourceTypeGathered' || !Number.isSafeInteger(q.condition.target))) throw Error('Unexpected quest condition');
  daily[type] = { steps: steps.map(q => ({ id: q.id, target: q.condition.target })), target: steps.at(-1).condition.target };
}
const mineData = Object.fromEntries(Object.values(mines).filter(m => ['food', 'wood', 'iron', 'stone'].includes(m.mineType)).map(m => {
  if (!(m.gatheringSpeedPerMinute > 0)) throw Error('Invalid mine speed');
  return [m.id, { type: m.mineType, level: m.level, amount: m.resourcesAmount, speedPerMinute: m.gatheringSpeedPerMinute }];
}));
await writeFile('extension/smart-gather-data.js', '// Generated by scripts/generate-smart-gather-data.mjs.\n' +
  'globalThis.hwaHelperSmartGatherData = ' + JSON.stringify({ sources, daily, mines: mineData }) + ';\n');
console.log('Generated verified daily gathering chains and 40 mine configurations.');
