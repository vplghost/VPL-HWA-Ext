import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parseRemoteDurationSeconds } from './lib/remote-duration.mjs';
const index = JSON.parse(await readFile('temp/remote-config-captured.json', 'utf8')).index.configs;
const data = {}, sources = {};
for (const type of ['speedUpConstruction', 'speedUpResearch', 'speedUpUnitHealing']) {
  const bytes = await readFile(`temp/items-current-${type}.json`);
  const md5 = createHash('md5').update(bytes).digest('hex'), url = index[type].url;
  if (!url.endsWith('/' + md5 + '.json')) throw Error('Speedup config hash mismatch: ' + type);
  sources[type] = { url, md5 };
  data[type] = Object.fromEntries(Object.values(JSON.parse(bytes)).map(row => {
    const durationMs = parseRemoteDurationSeconds(row.duration) * 1000;
    if (!Number.isSafeInteger(row.id) || row.id <= 0 || !Number.isSafeInteger(durationMs) || durationMs <= 0) throw Error('Invalid speedup duration');
    return [row.id, durationMs];
  }));
}
await writeFile('extension/speedup-data.js', '// Generated by scripts/generate-speedup-data.mjs; durations are milliseconds.\n' +
  'globalThis.hwaHelperSpeedupData = ' + JSON.stringify({ sources, durations: data }, null, 2) + ';\n');
console.log('Verified and packaged dedicated construction, research and healing speedup durations.');
