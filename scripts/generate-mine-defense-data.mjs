import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const index = JSON.parse(await readFile('temp/remote-config-captured.json', 'utf8')).index.configs;
const sources = {};
async function config(name, file) {
  const bytes = await readFile(file), md5 = createHash('md5').update(bytes).digest('hex');
  if (!index[name]?.url.endsWith(`/${md5}.json`)) throw Error(`Config MD5 mismatch: ${name}`);
  sources[name] = { url: index[name].url, md5 };
  return JSON.parse(bytes);
}
const buildings = await config('building', 'temp/building.json');
const levels = await config('buildingLevel', 'temp/buildingLevel.json');
const bonuses = await config('bonus', 'temp/defense-bonus.json');
const capacities = {};
for (const id of [162, 174, 175]) {
  if (!buildings[id]?.label.startsWith('Infirmary')) throw Error('Unexpected building');
  let total = 0, previous = 0;
  capacities[id] = { 0: 0 };
  for (const row of Object.values(levels).filter(r => r.buildingId === id).sort((a, b) => a.level - b.level)) {
    if (row.level !== previous + 1) throw Error('Incomplete infirmary levels');
    for (const reward of row.reward || []) {
      const bonus = reward.type === 'bonus' ? bonuses[reward.id] : null;
      if (bonus?.bonusType !== 'healingCapacity') continue;
      if (bonus.calculationType !== 'absolute' || !Number.isSafeInteger(bonus.value) || bonus.value < 0) throw Error('Unknown hospital bonus');
      total += bonus.value * reward.amount;
    }
    capacities[id][row.level] = total; previous = row.level;
  }
}
await writeFile('extension/mine-defense-data.js', '// Generated by scripts/generate-mine-defense-data.mjs.\n' +
  'globalThis.hwaHelperMineDefenseData = ' + JSON.stringify({ sources, capacities }) + ';\n');
console.log('Generated verified cumulative Infirmary capacities.');
