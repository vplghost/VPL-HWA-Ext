import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readZip, verifyAsset } from './sync-cdn-assets.mjs';

// The indexed splitlib container has two uint32 headers: index and row-data sizes.
// The protobuf index lists row IDs and cumulative row ends. Some tables append
// additional protobuf fields (magicTower has a packed template list).
function fields(bytes) {
  let offset = 0;
  function varint() {
    let value = 0, multiplier = 1;
    for (let count = 0; count < 8 && offset < bytes.length; count++) {
      const byte = bytes[offset++];
      value += (byte & 127) * multiplier;
      if (!Number.isSafeInteger(value)) throw Error('Unsafe protobuf integer');
      if (!(byte & 128)) return value;
      multiplier *= 128;
    }
    throw Error('Truncated protobuf varint');
  }
  const result = new Map();
  while (offset < bytes.length) {
    const tag = varint(), field = Math.floor(tag / 8), wire = tag % 8;
    if (!field) throw Error('Invalid protobuf field');
    let value;
    if (wire === 0) value = varint();
    else {
      const length = wire === 2 ? varint() : wire === 1 ? 8 : wire === 5 ? 4 : -1;
      if (length < 0 || offset + length > bytes.length) throw Error('Invalid protobuf length/wire');
      value = bytes.subarray(offset, offset + length);
      offset += length;
    }
    if (!result.has(field)) result.set(field, []);
    result.get(field).push(value);
  }
  return result;
}

export function indexedRows(bytes) {
  if (bytes.length < 8) throw Error('Truncated splitlib header');
  const indexSize = bytes.readUInt32LE(0), dataSize = bytes.readUInt32LE(4);
  const dataStart = 8 + indexSize, dataEnd = dataStart + dataSize;
  if (!indexSize || !dataSize || dataEnd > bytes.length) throw Error('Truncated splitlib data');
  const index = fields(bytes.subarray(8, dataStart));
  const rows = new Map();
  let start = 0;
  for (const entry of index.get(1) || []) {
    const item = fields(entry), id = item.get(1)?.[0], end = item.get(2)?.[0];
    if (!Number.isSafeInteger(id) || id < 1 || rows.has(id) ||
        !Number.isSafeInteger(end) || end <= start || end > dataSize) throw Error('Invalid splitlib index');
    const row = fields(bytes.subarray(dataStart + start, dataStart + end));
    if (row.get(1)?.[0] !== id) throw Error('Splitlib row ID mismatch');
    rows.set(id, row);
    start = end;
  }
  if (!rows.size || start !== dataSize) throw Error('Incomplete splitlib index');
  fields(bytes.subarray(dataEnd)); // Validate optional protobuf tail without treating it as rows.
  return rows;
}

export function deriveTowerRules(floorBytes, templateBytes) {
  const floors = indexedRows(floorBytes), templates = indexedRows(templateBytes);
  const ids = [...floors.keys()].sort((a, b) => a - b);
  const terminal = [];
  for (const [position, id] of ids.entries()) {
    if (id !== position + 1) throw Error('Non-contiguous Tower floors');
    const templateId = floors.get(id).get(2)?.[0];
    const template = templates.get(templateId);
    if (!template) throw Error('Missing Tower floor template');
    if (template.get(6)?.[0]?.toString('utf8') === 'MAGIC_TOWER_FLOORLAST_TITLE') {
      terminal.push({ floor: id, templateId });
    }
  }
  if (terminal.length !== 1 || terminal[0].floor !== ids.at(-1)) throw Error('Ambiguous Tower final floor');
  return { floorCount: ids.length, finalFloor: terminal[0].floor, finalTemplateId: terminal[0].templateId };
}

export async function generateTowerRules(archivePath, catalogPath, outputPath) {
  const catalog = JSON.parse(await readFile(catalogPath, 'utf8'));
  const archive = await readFile(archivePath);
  verifyAsset(archive, catalog.source.catalog);
  const zip = readZip(archive), files = ['magicTower.pb', 'magicTowerFloorTemplate.pb'];
  const buffers = files.map(name => {
    const bytes = zip.get(name);
    if (!bytes) throw Error('Missing splitlib table: ' + name);
    return bytes;
  });
  const rules = deriveTowerRules(...buffers);
  const source = {
    staticVersion: catalog.source.version,
    ...catalog.source.catalog,
    files: Object.fromEntries(files.map((name, i) => [name, {
      size: buffers[i].length, sha256: createHash('sha256').update(buffers[i]).digest('hex'),
    }])),
  };
  await writeFile(outputPath, '// Generated by scripts/generate-tower-rules.mjs; do not edit.\n' +
    'globalThis.hwaHelperTowerRules = ' + JSON.stringify({ ...rules, source }, null, 2) + ';\n');
  return rules;
}

