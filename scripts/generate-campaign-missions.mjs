import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const missionJsonPath = join(root, 'temp/splitlib/mission.json');
const outputPath = join(root, 'extension/campaign-missions.js');

const raw = await readFile(missionJsonPath, 'utf8');
const missionMap = JSON.parse(raw);

const missions = {};
const itemDrops = {};

for (const [idStr, data] of Object.entries(missionMap)) {
  const id = Number(idStr);
  // Main campaign missions have world between 1 and 15
  if (!data.world || data.world > 15 || id > 200) continue;

  const gears = new Set();
  const frags = new Set();
  const scrolls = new Set();
  const fragScrolls = new Set();

  for (const wave of data.normalMode?.waves || []) {
    for (const enemy of wave.enemies || []) {
      for (const drop of enemy.drop || []) {
        if (drop.reward?.gear) {
          for (const gId of Object.keys(drop.reward.gear)) {
            gears.add(Number(gId));
            (itemDrops[gId] = itemDrops[gId] || []).push(id);
          }
        }
        if (drop.reward?.fragmentGear) {
          for (const fId of Object.keys(drop.reward.fragmentGear)) {
            frags.add(Number(fId));
            (itemDrops[fId] = itemDrops[fId] || []).push(id);
          }
        }
        if (drop.reward?.scroll) {
          for (const sId of Object.keys(drop.reward.scroll)) {
            scrolls.add(Number(sId));
            (itemDrops[sId] = itemDrops[sId] || []).push(id);
          }
        }
        if (drop.reward?.fragmentScroll) {
          for (const sId of Object.keys(drop.reward.fragmentScroll)) {
            fragScrolls.add(Number(sId));
            (itemDrops[sId] = itemDrops[sId] || []).push(id);
          }
        }
      }
    }
  }

  missions[id] = {
    id,
    chapter: data.world,
    index: data.index,
    isHeroic: Boolean(data.isHeroic),
    cost: Number(data.normalMode?.cost?.stamina || 6),
    drops: {
      gear: [...gears],
      fragmentGear: [...frags],
      scroll: [...scrolls],
      fragmentScroll: [...fragScrolls]
    }
  };
}

// Deduplicate and sort mission lists
for (const k of Object.keys(itemDrops)) {
  itemDrops[k] = [...new Set(itemDrops[k])].sort((a, b) => a - b);
}

const jsContent = `// Generated by scripts/generate-campaign-missions.mjs. Do not edit manually.
(() => {
  const missions = ${JSON.stringify(missions, null, 2)};
  const itemDrops = ${JSON.stringify(itemDrops, null, 2)};

  function getMissionsForItem(itemId) {
    if (!itemId) return [];
    const strId = String(itemId);
    const ids = itemDrops[strId] || [];
    return ids.map((id) => missions[id]).filter(Boolean);
  }

  function getMissionProgress(missionId, missionProgressMap) {
    if (!missionProgressMap) return null;
    const numId = Number(missionId);
    if (Array.isArray(missionProgressMap)) {
      return missionProgressMap.find((m) => Number(m?.id) === numId) || null;
    }
    if (typeof missionProgressMap === 'object') {
      return missionProgressMap[String(missionId)] || missionProgressMap[numId] || null;
    }
    return null;
  }

  function getMissionTries(missionId, missionProgressMap) {
    const numId = Number(missionId);
    const m = missions[String(numId)];
    const isHeroic = Boolean(m?.isHeroic);
    if (!isHeroic) {
      return { isHeroic: false, maxTries: Infinity, triesSpent: 0, triesLeft: Infinity };
    }
    const progress = getMissionProgress(numId, missionProgressMap);
    const resetToday = Number(progress?.resetToday) || 0;
    const maxTries = (resetToday + 1) * 3;
    const triesSpent = Number(progress?.triesSpent) || 0;
    const triesLeft = Math.max(0, maxTries - triesSpent);
    return { isHeroic: true, maxTries, triesSpent, triesLeft };
  }

  function isMissionRaidable(missionId, missionProgressMap, options = {}) {
    const numId = Number(missionId);
    const m = missions[String(numId)];
    if (!m) return false;

    const disabledIds = options.disabledIds;
    if (disabledIds) {
      if (typeof disabledIds.has === 'function' && disabledIds.has(numId)) return false;
      if (Array.isArray(disabledIds) && disabledIds.includes(numId)) return false;
    }

    const progress = getMissionProgress(numId, missionProgressMap);
    if (!progress || !Number.isFinite(progress.stars) || progress.stars < 3) {
      return false;
    }

    if (m.isHeroic) {
      const tries = getMissionTries(numId, missionProgressMap);
      if (tries.triesLeft <= 0) return false;
    }

    return true;
  }

  function getHighestRaidableMission(candidateMissionIds, missionProgressMap, options = {}) {
    if (!candidateMissionIds || candidateMissionIds.length === 0) return null;
    const sorted = [...candidateMissionIds].sort((a, b) => Number(b) - Number(a));
    const threeStar = sorted.find((id) => {
      const progress = getMissionProgress(id, missionProgressMap);
      const is3Star = Number(progress?.stars) >= 3;
      return is3Star && isMissionRaidable(id, missionProgressMap, options);
    });
    if (threeStar != null) return Number(threeStar);

    const anyRaidable = sorted.find((id) => isMissionRaidable(id, missionProgressMap, options));
    if (anyRaidable != null) return Number(anyRaidable);

    return Number(sorted[0]);
  }

  globalThis.hwaHelperCampaignMissions = {
    missions,
    itemDrops,
    getMissionsForItem,
    getHighestRaidableMission,
    getMissionProgress,
    getMissionTries,
    isMissionRaidable
  };
})();
`;

await writeFile(outputPath, jsContent, 'utf8');
console.log(`Generated campaign missions data: ${Object.keys(missions).length} missions, ${Object.keys(itemDrops).length} drop items at ${outputPath}`);
