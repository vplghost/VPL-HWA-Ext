#!/usr/bin/env node
/**
 * Generates static Hero Glyph data (`src/data/glyphData.ts`) from game splitlib protobufs:
 * - temp/splitlib/hero_runes.pb      -> 117 heroes x 5 runeTypeIds (tier 0..4)
 * - temp/splitlib/rune_type.pb       -> 15 rune types x 81 stat values (Lv.0..80)
 * - temp/splitlib/rune_level_cost.pb -> 80 level costs (Lv.1..80: Rune Stones 40077 / Rune Spheres 40078)
 */
import fs from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');

function readVarint(buf, pos) {
  let r = 0n;
  let s = 0n;
  while (pos < buf.length) {
    const b = buf[pos++];
    r |= BigInt(b & 0x7f) << s;
    if (!(b & 0x80)) return [Number(r), pos];
    s += 7n;
  }
  return [Number(r), pos];
}

function parseRaw(buf) {
  const out = [];
  let pos = 0;
  while (pos < buf.length) {
    const [tag, p1] = readVarint(buf, pos);
    const fn = tag >> 3;
    const wt = tag & 7;
    pos = p1;
    if (wt === 0) {
      const [v, p2] = readVarint(buf, pos);
      pos = p2;
      out.push([fn, v]);
    } else if (wt === 2) {
      const [len, p2] = readVarint(buf, pos);
      pos = p2;
      out.push([fn, buf.subarray(pos, pos + len)]);
      pos += len;
    } else if (wt === 5) {
      out.push([fn, buf.readFloatLE(pos)]);
      pos += 4;
    } else if (wt === 1) {
      out.push([fn, buf.readDoubleLE(pos)]);
      pos += 8;
    } else {
      break;
    }
  }
  return out;
}

function unpackVarints(buf) {
  const arr = [];
  let p = 0;
  while (p < buf.length) {
    const [v, p2] = readVarint(buf, p);
    arr.push(v);
    p = p2;
  }
  return arr;
}

const RUNE_STAT_LABELS = {
  1: { key: 'strength', label: 'Strength', abbr: 'Str', icon: '💪' },
  2: { key: 'intelligence', label: 'Intelligence', abbr: 'Int', icon: '🧠' },
  3: { key: 'agility', label: 'Agility', abbr: 'Agi', icon: '🏃' },
  4: { key: 'health', label: 'Health', abbr: 'HP', icon: '❤️' },
  5: { key: 'physicalAttack', label: 'Physical Attack', abbr: 'PA', icon: '⚔️' },
  6: { key: 'magicAttack', label: 'Magic Attack', abbr: 'MA', icon: '✨' },
  7: { key: 'armor', label: 'Armor', abbr: 'Arm', icon: '🛡️' },
  8: { key: 'magicDefense', label: 'Magic Defense', abbr: 'MD', icon: '🔮' },
  9: { key: 'critHitChance', label: 'Crit Hit', abbr: 'Crit', icon: '🎯' },
  10: { key: 'dodge', label: 'Dodge', abbr: 'Ddg', icon: '💨' },
  11: { key: 'magicPenetration', label: 'Magic Pen', abbr: 'MP', icon: '⚡' },
  12: { key: 'armorPenetration', label: 'Armor Pen', abbr: 'AP', icon: '🗡️' },
  13: { key: 'magicCritHitChance', label: 'Magic Crit', abbr: 'MCrit', icon: '🌟' },
  14: { key: 'toughness', label: 'Toughness', abbr: 'Tough', icon: '🪨' },
  15: { key: 'crushing', label: 'Crushing', abbr: 'Crush', icon: '💥' },
};

const heroGlyphTypes = {};
for (const [, buf] of parseRaw(fs.readFileSync(resolve(ROOT, 'temp/splitlib/hero_runes.pb')))) {
  const fields = parseRaw(buf);
  const heroId = fields.find(([f]) => f === 1)?.[1];
  const types = fields
    .filter(([f]) => f === 2)
    .flatMap(([, x]) => (Buffer.isBuffer(x) ? unpackVarints(x) : [x]));
  if (Number.isInteger(heroId) && heroId > 0 && types.length >= 5) {
    heroGlyphTypes[heroId] = types.slice(0, 5);
  }
}

const glyphTypeMeta = {};
for (const [, buf] of parseRaw(fs.readFileSync(resolve(ROOT, 'temp/splitlib/rune_type.pb')))) {
  const fields = parseRaw(buf);
  const id = fields.find(([f]) => f === 1)?.[1];
  const valsBuf = fields.find(([f]) => f === 3)?.[1];
  const values = [];
  if (Buffer.isBuffer(valsBuf)) {
    for (let i = 0; i + 4 <= valsBuf.length; i += 4) {
      values.push(Math.round(valsBuf.readFloatLE(i)));
    }
  }
  const meta = RUNE_STAT_LABELS[id] || { key: `rune_${id}`, label: `Stat #${id}`, abbr: `S${id}`, icon: '✨' };
  if (Number.isInteger(id) && id > 0) {
    glyphTypeMeta[id] = { ...meta, values };
  }
}

const glyphLevelCosts = {};
for (const [, buf] of parseRaw(fs.readFileSync(resolve(ROOT, 'temp/splitlib/rune_level_cost.pb')))) {
  const fields = parseRaw(buf);
  const level = fields.find(([f]) => f === 1)?.[1];
  const heroLevel = fields.find(([f]) => f === 2)?.[1] ?? 20;
  let runeStones = 0;
  let runeSpheres = 0;
  for (const [, cb] of fields.filter(([f]) => f === 3)) {
    const cm = parseRaw(cb);
    const coinId = cm.find(([f]) => f === 2)?.[1];
    const amt = cm.find(([f]) => f === 3)?.[1] ?? 0;
    if (coinId === 40077) runeStones += amt;
    else if (coinId === 40078) runeSpheres += amt;
  }
  if (Number.isInteger(level) && level > 0) {
    glyphLevelCosts[level] = { heroLevel, runeStones, runeSpheres };
  }
}

const outPath = resolve(ROOT, 'src/data/glyphData.ts');
const ts = `// Auto-generated by scripts/generate-glyph-data.mjs from temp/splitlib/*.pb — do not edit manually.

export interface GlyphTypeMeta {
  key: string;
  label: string;
  abbr: string;
  icon: string;
  values: number[];
}

export interface GlyphLevelCost {
  heroLevel: number;
  runeStones: number;
  runeSpheres: number;
}

export const HERO_GLYPH_TYPES: Record<number, [number, number, number, number, number]> = ${JSON.stringify(heroGlyphTypes)};

export const GLYPH_TYPE_META: Record<number, GlyphTypeMeta> = ${JSON.stringify(glyphTypeMeta)};

export const GLYPH_LEVEL_COSTS: Record<number, GlyphLevelCost> = ${JSON.stringify(glyphLevelCosts)};
`;

fs.writeFileSync(outPath, ts, 'utf8');
console.log(
  `✓ Generated src/data/glyphData.ts (${Object.keys(heroGlyphTypes).length} heroes, ${Object.keys(glyphTypeMeta).length} types, ${Object.keys(glyphLevelCosts).length} level costs)`
);
