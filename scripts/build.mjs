import { execFile } from 'node:child_process';
import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { promisify } from 'node:util';
import { bumpVersion } from './bump-version.mjs';

const execFileAsync = promisify(execFile);

const root = resolve(import.meta.dirname, '..');
const source = join(root, 'extension');
const destination = join(root, 'dist');
const manifest = JSON.parse(await readFile(join(source, 'manifest.json'), 'utf8'));

if (manifest.manifest_version !== 3 || manifest.name !== 'HWA Helper') {
  throw new Error('Invalid extension manifest');
}

const referencedFiles = [
  manifest.background?.service_worker,
  manifest.action?.default_popup,
  ...manifest.content_scripts.flatMap((entry) => [...(entry.js ?? []), ...(entry.css ?? [])]),
].filter(Boolean);

for (const file of referencedFiles) {
  if (file.startsWith('/') || file.includes('..')) throw new Error(`Unsafe manifest path: ${file}`);
  if (!(await stat(join(source, file))).isFile()) throw new Error(`Missing file: ${file}`);
}

await rm(destination, { recursive: true, force: true });
await mkdir(destination, { recursive: true });
await cp(source, destination, { recursive: true });
await execFileAsync(process.execPath, [join(root, 'node_modules/@tailwindcss/cli/dist/index.mjs'),
  '-i', join(source, 'popup.css'), '-o', join(destination, 'popup.css'), '--minify'], { cwd: root });

// Build WXT Vue 3 bundle
try {
  await execFileAsync(process.execPath, [join(root, 'node_modules/wxt/bin/wxt.mjs'), 'build'], { cwd: root });
  const wxtOutput = join(root, '.output', 'chrome-mv3');
  await cp(join(wxtOutput, 'chunks'), join(destination, 'chunks'), { recursive: true });
  await cp(join(wxtOutput, 'popup.html'), join(destination, 'popup.html'));
  await cp(join(wxtOutput, 'assets'), join(destination, 'assets'), { recursive: true });

  // Remove obsolete legacy popup files from distribution bundle (replaced by WXT bundle)
  for (const obsolete of ['popup.js', 'popup-data.js', 'dashboard-data.js', 'export-name.js']) {
    await rm(join(destination, obsolete), { force: true });
  }

  console.log('Synchronized WXT Vue 3 bundle into dist (excluded obsolete legacy popup scripts)');
} catch (e) {
  console.warn('WXT build warning (fallback to legacy popup):', e.message);
}

const buildVersion = await bumpVersion(process.argv[2] || 'patch');
await cp(join(source, 'manifest.json'), join(destination, 'manifest.json'));
console.log('Build version: ' + buildVersion);
await writeFile(join(destination, '.build-info'), 'Generated by npm run build. Load this directory in Chrome.\n');
console.log(`Built extension at ${destination}`);
