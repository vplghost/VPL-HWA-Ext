import { execFile } from 'node:child_process';
import { cp, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { promisify } from 'node:util';
import { validateExtension } from './validate-extension.mjs';

const root = resolve(import.meta.dirname, '..');
const output = join(root, '.output', 'chrome-mv3');
const distDestination = join(root, 'dist');
const wxtBin = join(root, 'node_modules/wxt/bin/wxt.mjs');
const execFileAsync = promisify(execFile);

// 1. Build Production target into dist/ (VITE_DEBUG_BRIDGE=false)
console.log('Building Production extension (dist/)...');
await execFileAsync(process.execPath, [wxtBin, 'build'], {
  cwd: root,
  env: { ...process.env, VITE_DEBUG_BRIDGE: 'false' }
});
await validateExtension(output);
await rm(distDestination, { recursive: true, force: true });
await cp(output, distDestination, { recursive: true });
await writeFile(join(distDestination, '.build-info'), 'Generated by WXT for PRODUCTION. Load this directory for store release or clean distribution.\n');
console.log('✓ Built and validated Production extension at: ' + distDestination);

// 2. Build Debug / Unpacked target into .output/chrome-mv3 (VITE_DEBUG_BRIDGE=true)
console.log('Building Debug / Unpacked extension (.output/chrome-mv3)...');
await execFileAsync(process.execPath, [wxtBin, 'build'], {
  cwd: root,
  env: { ...process.env, VITE_DEBUG_BRIDGE: 'true' }
});
await validateExtension(output);
await writeFile(join(output, '.build-info'), 'Generated by WXT for DEBUG / UNPACKED. Native Messaging Bridge enabled. Load this directory in Chrome for development.\n');
console.log('✓ Built and validated Debug / Unpacked extension at: ' + output);

