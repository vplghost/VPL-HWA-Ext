import { execFile } from 'node:child_process';
import { cp, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { promisify } from 'node:util';
import { validateExtension } from './validate-extension.mjs';

const root = resolve(import.meta.dirname, '..');
const output = join(root, '.output', 'chrome-mv3');
const destination = join(root, 'dist');

// WXT is the sole compiler and manifest producer. Never fall back to legacy UI.
await promisify(execFile)(process.execPath,
  [join(root, 'node_modules/wxt/bin/wxt.mjs'), 'build'], { cwd: root });
await validateExtension(output);
// Both paths are fixed children of this repository, never user-supplied paths.
await rm(destination, { recursive: true, force: true });
await cp(output, destination, { recursive: true });
await writeFile(join(destination, '.build-info'), 'Generated by WXT via npm run build. Load this directory in Chrome.\n');
console.log('Built and validated WXT extension at ' + destination);
