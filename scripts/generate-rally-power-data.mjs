import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { readZip } from './sync-cdn-assets.mjs';

const root = resolve(import.meta.dirname, '..');
const md5 = bytes => createHash('md5').update(bytes).digest('hex');
const index = JSON.parse(await readFile(resolve(root, 'temp/remote-config-captured.json'), 'utf8')).index.configs;
const assetIndex = JSON.parse(await readFile(resolve(root, 'temp/asset-index-captured.json'), 'utf8'));
async function config(name) {
  const url = index[name]?.url;
  if (!url) throw Error('Missing config: ' + name);
  const path = resolve(root, `temp/rally-power-${name}.json`);
  let bytes;
  try { bytes = await readFile(path); }
  catch {
    const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
    if (!response.ok) throw Error(`${name}: HTTP ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
    if (!url.endsWith('/' + md5(bytes) + '.json')) throw Error('Config MD5 mismatch: ' + name);
    await writeFile(path, bytes);
  }
  if (!url.endsWith('/' + md5(bytes) + '.json')) throw Error('Cached config MD5 mismatch: ' + name);
  return { data: JSON.parse(bytes), source: { url, md5: md5(bytes) } };
}
function findAsset(value, path) {
  if (!value || typeof value !== 'object') return null;
  if (value.path === path) return value;
  for (const child of Object.values(value)) {
    const found = findAsset(child, path);
    if (found) return found;
  }
  return null;
}
const [units, squads, mobs] = await Promise.all(['unit', 'predefinedSquad', 'globalMapMobRally'].map(config));
const file = 'predefinedSquadHeroes.json';
const bytes = readZip(await readFile(resolve(root, 'temp/resources-splitlib.json.zip'))).get(file);
const expected = findAsset(assetIndex, file);
if (!bytes || !expected || bytes.length !== expected.size || md5(bytes) !== expected.md5) throw Error('Preset size/MD5 mismatch');
const heroes = JSON.parse(bytes);
const unitPower = Object.fromEntries(Object.values(units.data).map(row => {
  if (!Number.isInteger(row.id) || !Number.isFinite(row.power) || row.power < 0) throw Error('Invalid unit power');
  return [row.id, row.power];
}));
const bosses = {};
for (const mob of Object.values(mobs.data)) {
  if (mob.id !== 59 + mob.level || mob.level < 1 || mob.level > 30) continue;
  const squad = squads.data[mob.predefinedSquadId], heroPower = heroes[mob.predefinedSquadId]?.heroesPower;
  if (!Array.isArray(squad?.units) || !Number.isFinite(heroPower) || heroPower < 0) throw Error('Incomplete boss preset');
  let troops = 0, count = 0;
  for (const unit of squad.units) {
    if (!Number.isInteger(unit.count) || unit.count < 0 || unitPower[unit.unitId] == null) throw Error('Invalid boss units');
    count += unit.count; troops += unit.count * unitPower[unit.unitId];
  }
  bosses[mob.id] = { heroes: heroPower, troops, count, predefinedSquadId: mob.predefinedSquadId };
}
if (Object.keys(bosses).length !== 30) throw Error('Expected 30 distinct boss levels');
const source = { unit: units.source, predefinedSquad: squads.source, globalMapMobRally: mobs.source,
  heroesPreset: { path: file, size: expected.size, md5: expected.md5 } };
await writeFile(resolve(root, 'src/utils/rallyPowerData.ts'),
  '// Generated by scripts/generate-rally-power-data.mjs; do not edit.\n' +
  'export const RALLY_POWER_SOURCE = ' + JSON.stringify(source, null, 2) + ' as const;\n' +
  'export const UNIT_POWER: Record<number, number> = ' + JSON.stringify(unitPower) + ';\n' +
  'export const BOSS_POWER: Record<number, { heroes: number; troops: number; count: number; predefinedSquadId: number }> = ' + JSON.stringify(bosses, null, 2) + ';\n');
console.log('Generated verified unit power and 30 boss presets.');
