import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const index = JSON.parse(await readFile(resolve(root, 'temp/remote-config-captured.json'), 'utf8')).index.configs;
async function config(name) {
  const content = await readFile(resolve(root, 'temp/troop-limit-' + name + '.json'));
  const hash = createHash('md5').update(content).digest('hex');
  if (!index[name]?.url.endsWith('/' + hash + '.json')) throw Error('Config MD5 mismatch: ' + name);
  return JSON.parse(content);
}
const [levels, bonuses, mapping] = await Promise.all(['buildingLevel', 'bonus', 'unitsCapacityBonusMap'].map(config));
const bonusTypes = Object.values(mapping).map(row => row.bonusType);
const capacity = id => {
  const rows = Object.values(levels).filter(row => row.buildingId === id).sort((a, b) => a.level - b.level);
  const total = Object.fromEntries(bonusTypes.map(type => [type, 0]));
  return rows.map((row, position) => {
    if (row.level !== position + 1) throw Error('Missing level for building ' + id);
    for (const reward of row.reward || []) {
      const bonus = reward.type === 'bonus' ? bonuses[reward.id] : null;
      if (!bonusTypes.includes(bonus?.bonusType)) continue;
      if (bonus.calculationType !== 'absolute' || bonus.durationType !== 'permanent' || !Number.isSafeInteger(bonus.value)) throw Error('Unsupported capacity bonus');
      total[bonus.bonusType] += bonus.value * reward.amount;
    }
    return { ...total };
  });
};
// Latest game: only Drill Grounds contribute to troop stock capacity.
const grounds = [182, 183, 184].map(id => [0, ...capacity(id).map(row => {
  if (new Set(Object.values(row)).size !== 1) throw Error('Drill Grounds types differ');
  return row.unitsCapacityFront;
})]);
if (new Set(grounds.map(JSON.stringify)).size !== 1) throw Error('Building tables differ; generate separate tables');
await writeFile(resolve(root, 'src/utils/troopLimitData.ts'),
  '// Generated by scripts/generate-troop-limit-data.mjs; cumulative permanent absolute bonuses.\n' +
  '// ' + index.buildingLevel.url + '\n// ' + index.bonus.url + '\n// ' + index.unitsCapacityBonusMap.url + '\n' +
  'export const DRILL_GROUND_BUILDING_IDS = [182, 183, 184] as const;\n' +
  'export const DRILL_GROUND_LIMIT_BY_LEVEL = ' + JSON.stringify(grounds[0]) + ';\n');
console.log('Generated verified Drill Grounds capacity table (levels 0–25); legacy Camps excluded.');
